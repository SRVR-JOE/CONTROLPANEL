describe('addRack', () => {
  it('adds a rack with generated id and correct totalRU slots', () => {
    const { addRack } = useStore.getState();
    const rackSpec = makeRack({ totalRU: 5, width: 1 });
    const id = addRack(rackSpec);

    expect(typeof id).toBe('string');
    expect(id.length).toBeGreaterThan(0);

    const rack = useStore.getState().racks.find((r) => r.id === id);
    expect(rack).toBeDefined();
    expect(rack!.name).toBe('Test Rack');
    expect(rack!.totalRU).toBe(5);
    // Should have 5 slots (1 per RU for single-wide rack)
    expect(rack!.slots).toHaveLength(5);
  });

  it('creates all slots starting at RU 1 up to totalRU', () => {
    const { addRack } = useStore.getState();
    const id = addRack(makeRack({ totalRU: 3, width: 1 }));
    const rack = useStore.getState().racks.find((r) => r.id === id)!;
    const ruNumbers = rack.slots.map((s) => s.ru).sort((a, b) => a - b);
    expect(ruNumbers).toEqual([1, 2, 3]);
  });

  it('creates width * totalRU slots for multi-wide racks', () => {
    const { addRack } = useStore.getState();
    const id = addRack(makeRack({ totalRU: 4, width: 2 }));
    const rack = useStore.getState().racks.find((r) => r.id === id)!;
    // 2 columns x 4 RU each = 8 slots
    expect(rack!.slots).toHaveLength(8);
  });

  it('initialises all new slots with no deviceId', () => {
    const { addRack } = useStore.getState();
    const id = addRack(makeRack({ totalRU: 4 }));
    const rack = useStore.getState().racks.find((r) => r.id === id)!;
    rack.slots.forEach((s) => expect(s.deviceId).toBeUndefined());
  });
});

describe('removeRack', () => {
  it('removes the rack from the racks array', () => {
    const { addRack, removeRack } = useStore.getState();
    const id = addRack(makeRack());
    removeRack(id);
    const rack = useStore.getState().racks.find((r) => r.id === id);
    expect(rack).toBeUndefined();
  });

  it('clears rackId/rackSlot/rackColumn on devices that were in the removed rack', () => {
    const { addRack, addDevice, removeRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 5 }));
    const deviceId = addDevice(makeDevice({ rackId, rackSlot: 1, rackColumn: 0 }));

    removeRack(rackId);

    const device = useStore.getState().devices.find((d) => d.id === deviceId)!;
    expect(device.rackId).toBeUndefined();
    expect(device.rackSlot).toBeUndefined();
    expect(device.rackColumn).toBeUndefined();
  });

  it('does not affect devices in other racks', () => {
    const { addRack, addDevice, removeRack } = useStore.getState();
    const rackId1 = addRack(makeRack({ totalRU: 5 }));
    const rackId2 = addRack(makeRack({ totalRU: 5 }));
    const deviceId = addDevice(makeDevice({ rackId: rackId2, rackSlot: 1, rackColumn: 0 }));

    removeRack(rackId1);

    const device = useStore.getState().devices.find((d) => d.id === deviceId)!;
    expect(device.rackId).toBe(rackId2);
  });
});

