/**
 * Store action unit tests.
 *
 * Strategy: Each test calls useStore.getState() to get the action functions and
 * reads state directly, then uses useStore.setState() to reset between tests so
 * every test is fully isolated from the shared initial state.
 *
 * We do NOT mock uuid — it is a pure JS library that works fine in Node/jsdom.
 * We DO mock the window fetch (persistence layer) so network calls don't leak
 * out of tests and don't cause noise.
 */

import { describe, it, expect, beforeEach, vi } from 'vitest';
import { useStore } from '../index';
import type { Device, Rack } from '@/types';

// ============================================================
// Mock fetch so persistence flush-to-server calls don't error
// ============================================================
global.fetch = vi.fn().mockResolvedValue({ ok: true, json: async () => ({}) });

// ============================================================
// Helpers
// ============================================================

/** Build a minimal, valid device shape. */
function makeDevice(overrides: Partial<Device> = {}): Omit<Device, 'id'> {
  return {
    name: 'Test Device',
    manufacturer: 'blackmagic',
    model: 'Test Model',
    category: 'converter',
    status: 'online',
    rackUnits: 1,
    ports: [],
    health: { temperature: 30 },
    ...overrides,
  };
}

/** Build a minimal, valid rack shape (without id/slots — those are generated by addRack). */
function makeRack(overrides: Partial<Omit<Rack, 'id' | 'slots'>> = {}): Omit<Rack, 'id' | 'slots'> {
  return {
    name: 'Test Rack',
    location: 'Stage',
    width: 1,
    totalRU: 10,
    ...overrides,
  };
}

// ============================================================
// Reset store state between every test so tests are isolated
// ============================================================

/**
 * Capture a clean snapshot of the initial store state so we can
 * restore it cheaply between tests without re-importing the module.
 */
let initialSnapshot: ReturnType<typeof useStore.getState>;

beforeEach(() => {
  // On first run this captures the real initial state (with all mock devices/racks).
  // On subsequent runs we restore that snapshot.
  if (!initialSnapshot) {
    initialSnapshot = useStore.getState();
  } else {
    useStore.setState(initialSnapshot, true); // true = replace entire state
  }
  vi.clearAllMocks();
});

