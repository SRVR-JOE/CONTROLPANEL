describe('assignDeviceToRack', () => {
  it('assigns a 1U device to the correct rack slot', () => {
    const { addRack, addDevice, assignDeviceToRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 10 }));
    const deviceId = addDevice(makeDevice({ name: 'SDI Converter', rackUnits: 1 }));

    assignDeviceToRack(deviceId, rackId, 3, 0);

    const device = useStore.getState().devices.find((d) => d.id === deviceId)!;
    expect(device.rackId).toBe(rackId);
    expect(device.rackSlot).toBe(3);
    expect(device.rackColumn).toBe(0);

    const rack = useStore.getState().racks.find((r) => r.id === rackId)!;
    const slot = rack.slots.find((s) => s.ru === 3 && s.column === 0)!;
    expect(slot.deviceId).toBe(deviceId);
  });

  it('assigns a 4U device filling 4 consecutive slots', () => {
    const { addRack, addDevice, assignDeviceToRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 10 }));
    const deviceId = addDevice(makeDevice({ name: 'Media Server', rackUnits: 4 }));

    assignDeviceToRack(deviceId, rackId, 2, 0); // slots 2–5

    const rack = useStore.getState().racks.find((r) => r.id === rackId)!;
    for (let ru = 2; ru <= 5; ru++) {
      const slot = rack.slots.find((s) => s.ru === ru && s.column === 0)!;
      expect(slot.deviceId).toBe(deviceId);
    }
    // Slot 1 and 6 should remain empty
    expect(rack.slots.find((s) => s.ru === 1 && s.column === 0)!.deviceId).toBeUndefined();
    expect(rack.slots.find((s) => s.ru === 6 && s.column === 0)!.deviceId).toBeUndefined();
  });

  it('clears old rack slots when device is moved to a new position', () => {
    const { addRack, addDevice, assignDeviceToRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 10 }));
    const deviceId = addDevice(makeDevice({ rackUnits: 1 }));

    // Place at slot 1, then move to slot 5
    assignDeviceToRack(deviceId, rackId, 1, 0);
    assignDeviceToRack(deviceId, rackId, 5, 0);

    const rack = useStore.getState().racks.find((r) => r.id === rackId)!;
    // Old slot 1 must be cleared
    expect(rack.slots.find((s) => s.ru === 1 && s.column === 0)!.deviceId).toBeUndefined();
    // New slot 5 must be assigned
    expect(rack.slots.find((s) => s.ru === 5 && s.column === 0)!.deviceId).toBe(deviceId);
  });

  it('can move a device from one rack to another', () => {
    const { addRack, addDevice, assignDeviceToRack } = useStore.getState();
    const rack1Id = addRack(makeRack({ totalRU: 5, name: 'Rack A' }));
    const rack2Id = addRack(makeRack({ totalRU: 5, name: 'Rack B' }));
    const deviceId = addDevice(makeDevice({ rackUnits: 1 }));

    assignDeviceToRack(deviceId, rack1Id, 1, 0);
    assignDeviceToRack(deviceId, rack2Id, 3, 0);

    const rack1 = useStore.getState().racks.find((r) => r.id === rack1Id)!;
    const rack2 = useStore.getState().racks.find((r) => r.id === rack2Id)!;

    // Old rack slot is empty
    expect(rack1.slots.find((s) => s.ru === 1)!.deviceId).toBeUndefined();
    // New rack slot is filled
    expect(rack2.slots.find((s) => s.ru === 3)!.deviceId).toBe(deviceId);

    const device = useStore.getState().devices.find((d) => d.id === deviceId)!;
    expect(device.rackId).toBe(rack2Id);
    expect(device.rackSlot).toBe(3);
  });

  it('assigns to column 0 by default when no column is specified', () => {
    const { addRack, addDevice, assignDeviceToRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 5 }));
    const deviceId = addDevice(makeDevice({ rackUnits: 1 }));

    // Intentionally omit the column argument
    assignDeviceToRack(deviceId, rackId, 2);

    const device = useStore.getState().devices.find((d) => d.id === deviceId)!;
    expect(device.rackColumn).toBe(0);
  });

  it('assigns device to column 1 in a 2-wide rack', () => {
    const { addRack, addDevice, assignDeviceToRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 5, width: 2 }));
    const deviceId = addDevice(makeDevice({ rackUnits: 1 }));

    assignDeviceToRack(deviceId, rackId, 1, 1);

    const rack = useStore.getState().racks.find((r) => r.id === rackId)!;
    const slotCol0 = rack.slots.find((s) => s.ru === 1 && s.column === 0)!;
    const slotCol1 = rack.slots.find((s) => s.ru === 1 && s.column === 1)!;
    expect(slotCol0.deviceId).toBeUndefined();
    expect(slotCol1.deviceId).toBe(deviceId);
  });

  it('does nothing when the deviceId does not exist in the store', () => {
    const { addRack, assignDeviceToRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 5 }));
    const racksBefore = useStore.getState().racks;

    assignDeviceToRack('nonexistent-device', rackId, 1, 0);

    // Racks should be unchanged (or same reference)
    const racksAfter = useStore.getState().racks;
    expect(racksAfter).toBe(racksBefore);
  });
});

