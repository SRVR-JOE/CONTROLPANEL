describe('addDevice', () => {
  it('adds a device and returns a generated id', () => {
    const { addDevice } = useStore.getState();
    const id = addDevice(makeDevice({ name: 'New Device' }));
    expect(typeof id).toBe('string');
    const device = useStore.getState().devices.find((d) => d.id === id);
    expect(device).toBeDefined();
    expect(device!.name).toBe('New Device');
  });

  it('does not assign rack slots when device has no rackId', () => {
    const { addDevice } = useStore.getState();
    const id = addDevice(makeDevice({ name: 'Unassigned' }));
    const device = useStore.getState().devices.find((d) => d.id === id)!;
    expect(device.rackId).toBeUndefined();
  });

  it('assigns rack slot when device is added with rackId and rackSlot', () => {
    const { addRack, addDevice } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 5 }));
    const deviceId = addDevice(makeDevice({ rackId, rackSlot: 2, rackColumn: 0 }));

    const rack = useStore.getState().racks.find((r) => r.id === rackId)!;
    const slot = rack.slots.find((s) => s.ru === 2 && s.column === 0);
    expect(slot?.deviceId).toBe(deviceId);
  });
});

describe('removeDevice', () => {
  it('removes device from devices array', () => {
    const { addDevice, removeDevice } = useStore.getState();
    const id = addDevice(makeDevice());
    removeDevice(id);
    const found = useStore.getState().devices.find((d) => d.id === id);
    expect(found).toBeUndefined();
  });

  it('clears device from rack slots when removed', () => {
    const { addRack, addDevice, removeDevice } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 5 }));
    const deviceId = addDevice(makeDevice({ rackId, rackSlot: 1, rackColumn: 0 }));

    removeDevice(deviceId);

    const rack = useStore.getState().racks.find((r) => r.id === rackId)!;
    rack.slots.forEach((s) => expect(s.deviceId).toBeUndefined());
  });

  it('removes device from pin boards when removed', () => {
    const { addDevice, addPinBoardItem, removePinBoardItem: _, removeDevice } = useStore.getState();
    const deviceId = addDevice(makeDevice());
    const boardId = useStore.getState().pinBoards[0]?.id;
    if (!boardId) return; // No boards in state — skip

    useStore.getState().addPinBoardItem(boardId, {
      deviceId,
      position: { x: 0, y: 0 },
      size: { width: 200, height: 100 },
      showHealth: false,
      showTemperature: false,
      showPorts: false,
    });

    removeDevice(deviceId);

    const board = useStore.getState().pinBoards.find((b) => b.id === boardId)!;
    const item = board.items.find((i) => i.deviceId === deviceId);
    expect(item).toBeUndefined();
  });
});

