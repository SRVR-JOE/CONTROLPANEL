describe('removeDeviceFromRack', () => {
  it('clears rackId, rackSlot, and rackColumn from the device', () => {
    const { addRack, addDevice, assignDeviceToRack, removeDeviceFromRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 5 }));
    const deviceId = addDevice(makeDevice({ rackUnits: 1 }));
    assignDeviceToRack(deviceId, rackId, 2, 0);

    removeDeviceFromRack(deviceId);

    const device = useStore.getState().devices.find((d) => d.id === deviceId)!;
    expect(device.rackId).toBeUndefined();
    expect(device.rackSlot).toBeUndefined();
    expect(device.rackColumn).toBeUndefined();
  });

  it('clears all rack slots occupied by the device', () => {
    const { addRack, addDevice, assignDeviceToRack, removeDeviceFromRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 10 }));
    // 3U device occupies slots 4, 5, 6
    const deviceId = addDevice(makeDevice({ rackUnits: 3 }));
    assignDeviceToRack(deviceId, rackId, 4, 0);

    removeDeviceFromRack(deviceId);

    const rack = useStore.getState().racks.find((r) => r.id === rackId)!;
    for (let ru = 4; ru <= 6; ru++) {
      expect(rack.slots.find((s) => s.ru === ru)!.deviceId).toBeUndefined();
    }
  });

  it('leaves the device in the devices array (only removes rack assignment)', () => {
    const { addRack, addDevice, assignDeviceToRack, removeDeviceFromRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 5 }));
    const deviceId = addDevice(makeDevice({ name: 'Still Exists' }));
    assignDeviceToRack(deviceId, rackId, 1, 0);

    removeDeviceFromRack(deviceId);

    const device = useStore.getState().devices.find((d) => d.id === deviceId);
    expect(device).toBeDefined();
    expect(device!.name).toBe('Still Exists');
  });
});

