describe('multi-RU device slot coverage', () => {
  it('4U device at slot 1 occupies slots 1–4 and leaves slot 5 empty', () => {
    const { addRack, addDevice, assignDeviceToRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 5 }));
    const deviceId = addDevice(makeDevice({ rackUnits: 4 }));
    assignDeviceToRack(deviceId, rackId, 1, 0);

    const rack = useStore.getState().racks.find((r) => r.id === rackId)!;
    for (let ru = 1; ru <= 4; ru++) {
      expect(rack.slots.find((s) => s.ru === ru)!.deviceId).toBe(deviceId);
    }
    expect(rack.slots.find((s) => s.ru === 5)!.deviceId).toBeUndefined();
  });

  it('two separate devices placed at different slots do not overlap', () => {
    const { addRack, addDevice, assignDeviceToRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 10 }));
    const deviceA = addDevice(makeDevice({ name: 'Device A', rackUnits: 2 }));
    const deviceB = addDevice(makeDevice({ name: 'Device B', rackUnits: 2 }));

    assignDeviceToRack(deviceA, rackId, 1, 0); // occupies 1–2
    assignDeviceToRack(deviceB, rackId, 3, 0); // occupies 3–4

    const rack = useStore.getState().racks.find((r) => r.id === rackId)!;
    expect(rack.slots.find((s) => s.ru === 1)!.deviceId).toBe(deviceA);
    expect(rack.slots.find((s) => s.ru === 2)!.deviceId).toBe(deviceA);
    expect(rack.slots.find((s) => s.ru === 3)!.deviceId).toBe(deviceB);
    expect(rack.slots.find((s) => s.ru === 4)!.deviceId).toBe(deviceB);
  });

  it('reassigning a multi-RU device clears all its previous slots', () => {
    const { addRack, addDevice, assignDeviceToRack } = useStore.getState();
    const rackId = addRack(makeRack({ totalRU: 10 }));
    const deviceId = addDevice(makeDevice({ rackUnits: 3 }));

    assignDeviceToRack(deviceId, rackId, 1, 0); // slots 1, 2, 3
    assignDeviceToRack(deviceId, rackId, 5, 0); // slots 5, 6, 7

    const rack = useStore.getState().racks.find((r) => r.id === rackId)!;
    // Old slots must be clear
    expect(rack.slots.find((s) => s.ru === 1)!.deviceId).toBeUndefined();
    expect(rack.slots.find((s) => s.ru === 2)!.deviceId).toBeUndefined();
    expect(rack.slots.find((s) => s.ru === 3)!.deviceId).toBeUndefined();
    // New slots must be set
    expect(rack.slots.find((s) => s.ru === 5)!.deviceId).toBe(deviceId);
    expect(rack.slots.find((s) => s.ru === 6)!.deviceId).toBe(deviceId);
    expect(rack.slots.find((s) => s.ru === 7)!.deviceId).toBe(deviceId);
  });
});

